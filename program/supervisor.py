#!/usr/bin/env python3
"""Render or explicitly install a user service for TANGO's autonomous runner.

Rendering never activates a service. Installation is an explicit operator action.
The existing queue-only service is separate and is not started by this module.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import plistlib
import shutil
import subprocess
import sys
import tempfile


class SupervisorError(RuntimeError):
    pass


def checked_home(value):
    path = Path(value).expanduser()
    if path.is_symlink():
        raise SupervisorError('The TANGO home must not be a symlink')
    path = path.resolve()
    if not path.is_dir():
        raise SupervisorError('Install TANGO into an existing home first')
    return path


def identity(home):
    digest = hashlib.sha256(str(Path(home).resolve()).encode()).hexdigest()[:16]
    return 'com.tango.autonomous.' + digest


def executable(value, label):
    candidate = shutil.which(str(value))
    if candidate is None:
        raise SupervisorError(f'{label} executable not found: {value}')
    path = Path(candidate).resolve()
    if not path.is_file() or not os.access(path, os.X_OK):
        raise SupervisorError(f'{label} is not an executable regular file')
    return str(path)


def validate_python(path):
    result = subprocess.run([path, '-c', 'import sys; print("%d.%d" % sys.version_info[:2])'],
                            capture_output=True, text=True, timeout=10)
    try:
        major, minor = map(int, result.stdout.strip().split('.'))
    except ValueError as exc:
        raise SupervisorError('Could not determine the selected Python version') from exc
    if result.returncode or (major, minor) < (3, 10):
        raise SupervisorError('The service requires Python 3.10 or later')


def systemd_path(value):
    # Avoid specifier/variable expansion and ambiguous escaping in unit fields.
    # Ordinary spaces and Unicode paths are supported; unusual names fail closed.
    value = str(value)
    if any(ord(c) < 32 or ord(c) == 127 or c in '%$"\\' for c in value):
        raise SupervisorError('Linux service paths cannot contain control characters, %, $, quotes, or backslashes')
    return value


def service_spec(home, python=None, codex='codex', system=None):
    home = checked_home(home)
    system = system or platform.system()
    if system not in {'Linux', 'Darwin'}:
        raise SupervisorError('User services are supported on Linux and macOS only')
    program = home / 'program' / 'autonomous.py'
    if not program.is_file() or program.is_symlink():
        raise SupervisorError('The installed home has no regular program/autonomous.py')
    python = executable(python or sys.executable, 'Python')
    validate_python(python)
    codex = executable(codex, 'Codex')
    label = identity(home)
    argv = [python, '-B', str(program), '--home', str(home), '--codex', codex, 'run']
    logdir = home / 'service-logs'
    stdout = str(logdir / 'autonomous.stdout.log')
    stderr = str(logdir / 'autonomous.stderr.log')
    search_path = os.pathsep.join(dict.fromkeys([
        str(Path(python).parent), str(Path(codex).parent),
        '/usr/local/bin', '/usr/bin', '/bin', '/usr/sbin', '/sbin',
    ]))
    if system == 'Darwin':
        value = {
            'Label': label,
            'ProgramArguments': argv,
            'WorkingDirectory': str(home),
            'EnvironmentVariables': {'PATH': search_path, 'PYTHONUNBUFFERED': '1'},
            'RunAtLoad': True,
            'KeepAlive': {'SuccessfulExit': False},
            'ThrottleInterval': 15,
            'ExitTimeOut': 45,
            'Umask': 0o077,
            'StandardOutPath': stdout,
            'StandardErrorPath': stderr,
        }
        content = plistlib.dumps(value, fmt=plistlib.FMT_XML, sort_keys=False)
        filename = label + '.plist'
        scope = 'The LaunchAgent runs while this user is logged in; it resumes at the next login.'
    else:
        for value in argv + [stdout, stderr, search_path]:
            systemd_path(value)
        command = ' '.join('"' + item + '"' for item in argv)
        content = (
            '# Generated by TANGO; managed per installation home.\n'
            '[Unit]\nDescription=TANGO autonomous task runner\nStartLimitIntervalSec=0\n\n'
            '[Service]\nType=simple\n'
            f'WorkingDirectory={home}\nExecStart={command}\n'
            f'Environment="PATH={search_path}" "PYTHONUNBUFFERED=1"\n'
            'Restart=on-failure\nRestartSec=15s\nTimeoutStopSec=45s\n'
            'KillMode=control-group\nUMask=0077\n'
            f'StandardOutput=append:{stdout}\nStandardError=append:{stderr}\n\n'
            '[Install]\nWantedBy=default.target\n'
        ).encode('utf-8')
        filename = label + '.service'
        scope = 'Persistence beyond logout depends on the systemd user manager; lingering is not enabled by TANGO.'
    return {'system': system, 'label': label, 'filename': filename,
            'content': content, 'argv': argv, 'home': home, 'logdir': logdir,
            'session_scope': scope}


def private_directory(path):
    if path.is_symlink():
        raise SupervisorError(f'Symlink directory refused: {path}')
    path.mkdir(parents=True, exist_ok=True, mode=0o700)
    if not path.is_dir():
        raise SupervisorError(f'Expected a directory: {path}')


def write_private(path, content):
    if path.is_symlink():
        raise SupervisorError(f'Symlink file refused: {path}')
    private_directory(path.parent)
    if path.exists() and not path.is_file():
        raise SupervisorError(f'Expected a regular file: {path}')
    fd, temporary = tempfile.mkstemp(prefix='.' + path.name + '.', dir=path.parent)
    try:
        with os.fdopen(fd, 'wb') as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(temporary, 0o600)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def render(home, output, python=None, codex='codex', system=None):
    spec = service_spec(home, python, codex, system)
    destination = Path(output).expanduser().absolute() / spec['filename']
    if destination.is_symlink():
        raise SupervisorError('Render output must not be a symlink')
    if destination.exists() and destination.read_bytes() != spec['content']:
        raise SupervisorError('Render output already exists with different contents')
    write_private(destination, spec['content'])
    return {'rendered': str(destination), 'activated': False,
            'label': spec['label'], 'command': spec['argv'],
            'session_scope': spec['session_scope']}


def service_target(home, system=None):
    system = system or platform.system()
    label = identity(home)
    if system == 'Darwin':
        return Path.home() / 'Library' / 'LaunchAgents' / (label + '.plist')
    if system == 'Linux':
        configured = os.environ.get('XDG_CONFIG_HOME')
        base = Path(configured).expanduser() if configured else Path.home() / '.config'
        if not base.is_absolute():
            raise SupervisorError('XDG_CONFIG_HOME must be an absolute path')
        return base / 'systemd' / 'user' / (label + '.service')
    raise SupervisorError('User services are supported on Linux and macOS only')


def manager_command(system):
    name = 'launchctl' if system == 'Darwin' else 'systemctl'
    command = shutil.which(name)
    if command is None:
        raise SupervisorError(f'{name} is not available on this host')
    return command


def invoke(argv, required=True):
    result = subprocess.run(argv, capture_output=True, text=True, timeout=45)
    if required and result.returncode:
        # Service-manager diagnostics may contain paths, but not environment dumps.
        message = (result.stderr or result.stdout or 'no diagnostic').strip()[-2000:]
        raise SupervisorError(f'Service manager returned {result.returncode}: {message}')
    return result


def record_path(home):
    return Path(home) / 'service-manager.json'


def read_record(home):
    path = record_path(home)
    if path.is_symlink():
        raise SupervisorError('Service registration record must not be a symlink')
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding='utf-8'))
    except (ValueError, OSError) as exc:
        raise SupervisorError('Service registration record is unreadable') from exc


def managed_record(home, target):
    record = read_record(home)
    if not record or record.get('label') != identity(home) or record.get('path') != str(target):
        raise SupervisorError('No matching TANGO service registration; refusing to overwrite or remove the file')
    if target.is_symlink() or not target.is_file():
        raise SupervisorError('Registered service file is missing or is not a regular file')
    if hashlib.sha256(target.read_bytes()).hexdigest() != record.get('sha256'):
        raise SupervisorError('Registered service file changed; inspect it before replacing or removing it')
    return record


def install_service(home, python=None, codex='codex'):
    spec = service_spec(home, python, codex)
    home, system = spec['home'], spec['system']
    target = service_target(home, system)
    manager = manager_command(system)
    if target.exists() or target.is_symlink():
        managed_record(home, target)
        if target.read_bytes() != spec['content']:
            raise SupervisorError('Service configuration changed; uninstall the old service before installing the new configuration')
    private_directory(spec['logdir'])
    for name in ['autonomous.stdout.log', 'autonomous.stderr.log']:
        log = spec['logdir'] / name
        if log.is_symlink() or (log.exists() and not log.is_file()):
            raise SupervisorError('Service log path is not a regular file')
        fd = os.open(log, os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o600)
        os.close(fd)
        os.chmod(log, 0o600)
    write_private(target, spec['content'])
    record = {'label': spec['label'], 'system': system, 'path': str(target),
              'sha256': hashlib.sha256(spec['content']).hexdigest(), 'activation_requested': False}
    write_private(record_path(home), (json.dumps(record, indent=2) + '\n').encode())
    if system == 'Linux':
        invoke([manager, '--user', 'daemon-reload'])
        invoke([manager, '--user', 'enable', '--now', spec['filename']])
    else:
        domain = f'gui/{os.getuid()}'
        current = invoke([manager, 'print', domain + '/' + spec['label']], required=False)
        if current.returncode:
            invoke([manager, 'bootstrap', domain, str(target)])
        else:
            # No -k: repeated installation must not interrupt an active attempt.
            invoke([manager, 'kickstart', domain + '/' + spec['label']])
    record['activation_requested'] = True
    write_private(record_path(home), (json.dumps(record, indent=2) + '\n').encode())
    return {'registered': True, 'activation_requested': True, 'path': str(target),
            'label': spec['label'], 'session_scope': spec['session_scope'],
            'note': 'Inspect supervisor status and runner diagnostics; registration alone is not task acceptance.'}


def status(home):
    home = checked_home(home)
    system = platform.system()
    target = service_target(home, system)
    result = {'label': identity(home), 'path': str(target), 'registered': False,
              'manager_active': False, 'task_completion_verified': False}
    if not target.exists() and not target.is_symlink():
        return result
    managed_record(home, target)
    result['registered'] = True
    manager = manager_command(system)
    if system == 'Linux':
        query = invoke([manager, '--user', 'is-active', target.name], required=False)
        result['manager_active'] = query.returncode == 0
        result['manager_status'] = query.stdout.strip()[:200]
    else:
        query = invoke([manager, 'print', f'gui/{os.getuid()}/' + identity(home)], required=False)
        result['manager_loaded'] = query.returncode == 0
        result['manager_active'] = query.returncode == 0 and 'state = running' in query.stdout
    # Do not confuse a stale runner status file with current process liveness.
    result['runner_status_file'] = str(home / 'autonomous' / 'status.json')
    return result


def uninstall_service(home):
    home = checked_home(home)
    system = platform.system()
    target = service_target(home, system)
    if not target.exists() and not target.is_symlink():
        return {'removed': False, 'reason': 'No service file is installed', 'task_data_retained': True}
    managed_record(home, target)
    manager = manager_command(system)
    if system == 'Linux':
        invoke([manager, '--user', 'disable', '--now', target.name])
    else:
        service = f'gui/{os.getuid()}/' + identity(home)
        if invoke([manager, 'print', service], required=False).returncode == 0:
            invoke([manager, 'bootout', service])
    target.unlink()
    if system == 'Linux':
        invoke([manager, '--user', 'daemon-reload'])
    record_path(home).unlink()
    return {'removed': True, 'label': identity(home), 'task_data_retained': True,
            'note': 'The runner service is stopped; task goals, checkpoints, results, and logs are retained.'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--home', type=Path, required=True)
    parser.add_argument('--python', default=sys.executable)
    parser.add_argument('--codex', default='codex')
    commands = parser.add_subparsers(dest='command', required=True)
    render_parser = commands.add_parser('render', help='Write a service file for inspection without activation')
    render_parser.add_argument('--output', type=Path, required=True)
    render_parser.add_argument('--platform', choices=['Linux', 'Darwin'], default=None)
    commands.add_parser('install', help='Explicitly register and start a user service on this computer')
    commands.add_parser('status', help='Inspect the registered user service')
    commands.add_parser('uninstall', help='Stop and remove the registered service while retaining task data')
    args = parser.parse_args()
    try:
        if args.command == 'render':
            result = render(args.home, args.output, args.python, args.codex, args.platform)
        elif args.command == 'install':
            result = install_service(args.home, args.python, args.codex)
        elif args.command == 'status':
            result = status(args.home)
        else:
            result = uninstall_service(args.home)
        print(json.dumps(result, indent=2, sort_keys=True))
    except (OSError, ValueError, subprocess.TimeoutExpired, SupervisorError) as exc:
        parser.exit(2, f'Supervisor action failed: {exc}\n')


if __name__ == '__main__':
    main()
